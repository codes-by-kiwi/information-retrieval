import tqdm
def read_collection(f_path):
  collection = {}
  with open(f_path, "r") as fp:
    for line in tqdm.tqdm(fp, desc="reading {}".format(f_path)):
      did, dtext = line.strip().split("\t")
      collection[did] = dtext
  return collection

